namespace GHIElectronics.TinyCLR.UI {
    /// <summary>Describes how a child element is vertically positioned or stretched within its parent.</summary>
    public enum VerticalAlignment {
        /// <summary>Aligns the element to the top of the parent's layout slot.</summary>
        Top,
        /// <summary>Centers the element vertically within the parent's layout slot.</summary>
        Center,
        /// <summary>Aligns the element to the bottom of the parent's layout slot.</summary>
        Bottom,
        /// <summary>Stretches the element to fill the parent's layout slot vertically.</summary>
        Stretch
    }
}


