namespace GHIElectronics.TinyCLR.UI {
    /// <summary>Describes how a child element is horizontally positioned or stretched within its parent.</summary>
    public enum HorizontalAlignment {
        /// <summary>Aligns the element to the left of the parent's layout slot.</summary>
        Left,
        /// <summary>Centers the element horizontally within the parent's layout slot.</summary>
        Center,
        /// <summary>Aligns the element to the right of the parent's layout slot.</summary>
        Right,
        /// <summary>Stretches the element to fill the parent's layout slot horizontally.</summary>
        Stretch
    }
}


